#pragma once

#include <stdint.h>
#include <math.h>

// Pure, stateless animation math. No WLED dependencies: suitable for host tests.
namespace RGBBridgeEventFX {

enum class Effect : uint8_t { Projectile, Shockwave, Flash, Pulse, Progress, Sparks };

struct Color {
  uint8_t r, g, b;
};

struct Params {
  Effect effect = Effect::Projectile;
  uint16_t durationMs = 350;
  Color color = {255, 0, 0};
  Color colorA = {255, 230, 160};
  Color colorB = {255, 69, 0};
  bool hasSecondSparkColor = false;
  uint8_t pointSize = 2;
  uint8_t tailSize = 5;
  uint8_t waveWidth = 3;
  uint8_t pulses = 2;
  uint16_t holdMs = 40;
  uint8_t sparkDensity = 12; // Probability (percent) per LED per spark interval.
  uint16_t sparkLifeMs = 90;
};

struct Pixel {
  Color color = {0, 0, 0};
  float alpha = 0.0f;
  // Used by Shockwave: initial A-colored center overlays the expanding wave.
  Color center = {0, 0, 0};
  float centerAlpha = 0.0f;
};

inline float clamp01(float a) {
  return a < 0.0f ? 0.0f : (a > 1.0f ? 1.0f : a);
}
inline float smooth01(float x) {
  x = clamp01(x);
  return x*x*(3.0f - 2.0f*x);
}
inline uint8_t mixByte(uint8_t a, uint8_t b, float t) {
  return uint8_t(float(a) + (float(b) - float(a))*clamp01(t) + 0.5f);
}
inline Color mixColor(Color a, Color b, float t) {
  return { mixByte(a.r,b.r,t), mixByte(a.g,b.g,t), mixByte(a.b,b.b,t) };
}
inline uint32_t hash32(uint32_t x) {
  x ^= x >> 16; x *= 0x7feb352dUL;
  x ^= x >> 15; x *= 0x846ca68bUL;
  return x ^ (x >> 16);
}
inline float projectileAt(float head, uint16_t pixel, uint8_t pointSize, uint8_t tailSize) {
  const float lead = clamp01(head - float(pixel));
  const float back = clamp01(float(pixel + 1U) - (head - pointSize));
  const float point = fminf(lead, back);
  float tail = 0.0f;
  if (tailSize != 0) {
    const float behind = (head - pointSize) - (float(pixel) + 0.5f);
    if (behind >= 0.0f && behind < tailSize)
      tail = 0.72f * (1.0f - behind / float(tailSize));
  }
  return fmaxf(point, tail);
}

// elapsed and duration are identical across all selected segments. Geometry
// uses each segment's own virtual LED count; all effects end together.
inline Pixel render(const Params& cfg, uint16_t led, uint16_t count,
                    uint32_t elapsedMs, uint32_t seed) {
  Pixel result;
  if (!count || led >= count || elapsedMs >= cfg.durationMs || !cfg.durationMs)
    return result;
  const float p = float(elapsedMs) / float(cfg.durationMs);
  result.color = cfg.color;

  switch (cfg.effect) {
    case Effect::Projectile: {
      // The full point AND tail have left by the end of durationMs.
      const float head = p * float(count + cfg.pointSize + cfg.tailSize);
      result.alpha = projectileAt(head, led, cfg.pointSize, cfg.tailSize);
      break;
    }
    case Effect::Shockwave: {
      const float center = (float(count) - 1.0f) * 0.5f;
      const float dist = fabsf(float(led) - center);
      const float width = float(cfg.waveWidth);
      const float edge = (float(count) - 1.0f) * 0.5f;
      // AI: below section was generated by an AI
      // Use a one-LED antialiased front and a linear fading tail, like Projectile.
      // Travel includes the whole tail beyond both endpoints within durationMs.
      // waveWidth remains the configured trailing width; colors retain B -> A.
      const float radius = p * (edge + 1.0f + width);
      const float behind = radius - dist;
      result.alpha = clamp01(behind) * clamp01((1.0f + width - behind) / width);
      result.color = mixColor(cfg.colorB, cfg.colorA, clamp01(behind / width));
      // AI: end
      // Center bloom A at the beginning, fading as the ring moves away.
      const float bloom = clamp01(1.0f - p / 0.30f);
      const float centerSpread = fmaxf(0.75f, width * 0.7f);
      result.center = cfg.colorA;
      result.centerAlpha = clamp01(expf(-dist / centerSpread) * bloom * 1.2f);
      break;
    }
    case Effect::Flash: {
      const uint32_t hold = cfg.holdMs < cfg.durationMs ? cfg.holdMs : cfg.durationMs - 1U;
      const float x = elapsedMs <= hold ? 0.0f :
          float(elapsedMs - hold) / float(cfg.durationMs - hold);
      result.alpha = 1.0f - smooth01(x);
      break;
    }
    case Effect::Pulse: {
      const float phase = p * float(cfg.pulses);
      const float fraction = phase - floorf(phase);
      result.alpha = sinf(3.14159265359f * fraction);
      break;
    }
    case Effect::Progress: {
      const float filled = p * float(count);
      result.alpha = clamp01(filled - float(led));
      break;
    }
    case Effect::Sparks: {
      const uint32_t interval = cfg.sparkLifeMs;
      const uint32_t slot = elapsedMs / interval;
      const uint32_t salt = hash32(seed ^ (uint32_t(led + 1U)*0x9e3779b9UL));
      float best = 0.0f;
      uint32_t bestHash = 0;
      // An individual spark fades for two intervals, without allocating state.
      for (uint8_t offset = 0; offset <= 1; ++offset) {
        if (slot < offset) break;
        const uint32_t bucket = slot - offset;
        const uint32_t h = hash32(salt ^ (bucket * 0x85ebca6bUL));
        if (h % 100U >= cfg.sparkDensity) continue;
        const uint32_t born = bucket * interval;
        const float age = float(elapsedMs - born) / float(interval * 2U);
        const float intensity = 1.0f - smooth01(age);
        if (intensity > best) { best = intensity; bestHash = h; }
      }
      // Fade sparks out as the whole event reaches its deadline.
      const uint32_t left = cfg.durationMs - elapsedMs;
      result.alpha = best * clamp01(float(left)/float(interval));
      if (cfg.hasSecondSparkColor && (bestHash & 1U)) result.color = cfg.colorB;
      break;
    }
  }
  result.alpha = clamp01(result.alpha);
  result.centerAlpha = clamp01(result.centerAlpha);
  return result;
}

} // namespace RGBBridgeEventFX
