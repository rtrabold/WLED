// RGBBridge Event FX v1.4.3: WLED main, ESP32, 1D segments.
// Draws ABOVE WLED's current effects. Never changes fx, preset, or segment mode.
#include "wled.h"
#include "EventFxLogic.h"
#include <string.h>

class RGBBridgeEventFXUsermod : public Usermod {
private:
  using Color  = RGBBridgeEventFX::Color;
  using Effect = RGBBridgeEventFX::Effect;
  using Params = RGBBridgeEventFX::Params;
  using Pixel  = RGBBridgeEventFX::Pixel;

  // A shot may contain several segment-specific effect definitions. Keep the
  // shot limit independent from that definition count so configuring one
  // segment differently does not reduce burst capacity.
  static constexpr uint8_t MAX_SHOTS = 8;
  static constexpr uint8_t MAX_EFFECTS_PER_SHOT = 8;
  static constexpr uint8_t MAX_EVENTS = MAX_SHOTS * MAX_EFFECTS_PER_SHOT;
  static constexpr uint8_t MAX_SEGMENTS = 64;
  static constexpr uint32_t FRAME_MS = 24; // ~41 FPS. Actual FPS is WLED-limited.

  struct Event {
    bool active = false;
    uint32_t startMs = 0;
    uint32_t shotSequence = 0;
    uint32_t sequence = 0;
    uint64_t segmentMask = 0;
    Params params;
    Color background = {0, 0, 0};
    bool overlay = true;
    bool reverse = false;
    uint8_t brightness = 255;
  };

  Event events[MAX_EVENTS];
  uint32_t nextShotSequence = 0;
  uint32_t nextSequence = 0;
  uint32_t lastKickMs = 0;
  bool initDone = false;
  // AI: below section was generated by an AI
  uint32_t acceptedShots = 0, evictedShots = 0;
  uint32_t activeFrames = 0, maxActiveFrameGapMs = 0, previousFrameMs = 0;
  bool previousFrameActive = false;
  // AI: end

  // AI: below section was generated by an AI
  // Keep return timing separate from the eight shot slots: an expired shot
  // can be reused during a burst without losing another segment's fade.
  struct ReturnFade {
    bool active = false;
    uint32_t startMs = 0;
    uint16_t durationMs = 0;
    uint16_t start = 0, stop = 0;
    uint32_t background = 0;
  };
  ReturnFade returns[MAX_SEGMENTS];
  uint16_t returnFadeMs = 300;

  // Blend the solid background into the freshly rendered native effect.
  // No effect buffers, segment brightness, preset or mode are modified.
  void drawReturn(unsigned id, const Segment& segment, uint32_t now) {
    ReturnFade& fade = returns[id];
    if (!fade.active) return;
    const uint32_t elapsed = now - fade.startMs;
    if (!segment.isActive() || !segment.on || segment.is2D() ||
        segment.start != fade.start || segment.stop != fade.stop ||
        fade.durationMs == 0 || elapsed >= fade.durationMs) {
      fade.active = false;
      return;
    }
    const uint8_t progress = uint8_t(elapsed * 255UL / fade.durationMs);
    const unsigned end = std::min(unsigned(segment.stop), unsigned(strip.getLengthTotal()));
    for (unsigned pixel = segment.start; pixel < end; ++pixel)
      strip.setPixelColor(pixel, color_blend(fade.background, strip.getPixelColorNoMap(pixel), progress));
  }
  // AI: end

  static int bound(int value, int lo, int hi) {
    return value < lo ? lo : (value > hi ? hi : value);
  }

  static void readColor(JsonObject& command, const char* key, Color& dest) {
    JsonArray color = command[key].as<JsonArray>();
    if (color.isNull() || color.size() < 3) return;
    dest.r = uint8_t(bound(color[0].as<int>(), 0, 255));
    dest.g = uint8_t(bound(color[1].as<int>(), 0, 255));
    dest.b = uint8_t(bound(color[2].as<int>(), 0, 255));
  }

  // The wire protocol has exactly ONE command name and six valid effect IDs.
  // Reject mistakes rather than silently playing Projectile.
  static bool readEffect(JsonObject& command, Effect& effect) {
    const char* name = command["effect"] | "";
    if (!strcmp(name, "projectile")) { effect = Effect::Projectile; return true; }
    if (!strcmp(name, "shockwave"))  { effect = Effect::Shockwave;  return true; }
    if (!strcmp(name, "flash"))      { effect = Effect::Flash;      return true; }
    if (!strcmp(name, "pulse"))      { effect = Effect::Pulse;      return true; }
    if (!strcmp(name, "progress"))   { effect = Effect::Progress;   return true; }
    if (!strcmp(name, "sparks"))     { effect = Effect::Sparks;     return true; }
    return false;
  }

  static bool isLive(const Event& event, uint32_t now) {
    return event.active && uint32_t(now - event.startMs) < event.params.durationMs;
  }

  static void fillBackground(const Segment& seg, Color background, uint8_t brightness) {
    if (!seg.isActive() || !seg.on || seg.is2D()) return;
    const uint32_t packed = color_fade(RGBW32(background.r, background.g, background.b, 0), brightness);
    const uint32_t stop = seg.stop < strip.getLengthTotal()
      ? seg.stop : strip.getLengthTotal();
    for (uint32_t addr = seg.start; addr < stop; ++addr)
      strip.setPixelColor(addr, packed);
  }

  // The same virtual pixel is translated to real pixels as in RGBBridge Fire
  // v0.2. Compatible with WLED segment reverse, mirror, grouping and offset.
  static void blendPhysicalPixel(const Segment& seg, unsigned relative,
                                 Color color, uint8_t alpha) {
    if (!alpha || !seg.length()) return;
    const unsigned addr = seg.start + (relative + seg.offset) % seg.length();
    if (addr >= strip.getLengthTotal()) return;
    const uint32_t base = strip.getPixelColor(addr);
    const uint32_t foreground = RGBW32(color.r, color.g, color.b, uint8_t(base >> 24));
    strip.setPixelColor(addr, color_blend(base, foreground, alpha));
  }

  static void blendLogicalPixel(const Segment& seg, unsigned logical,
                                bool extraReverse, Color color, uint8_t alpha) {
    if (!alpha || !seg.virtualLength() || !seg.groupLength()) return;
    if (bool(seg.reverse) != extraReverse)
      logical = seg.virtualLength() - 1U - logical;
    const unsigned first = logical * seg.groupLength();
    for (unsigned g = 0; g < seg.grouping; ++g) {
      const unsigned relative = first + g;
      if (relative >= seg.length()) break;
      blendPhysicalPixel(seg, relative, color, alpha);
      if (seg.mirror) {
        const unsigned mirrored = seg.length() - relative - 1U;
        if (mirrored != relative)
          blendPhysicalPixel(seg, mirrored, color, alpha);
      }
    }
  }

  static uint8_t opacityFor(const Event& event, float alpha) {
    const float level = RGBBridgeEventFX::clamp01(alpha)
      * float(event.brightness) / 255.0f;
    return uint8_t(level * 255.0f + 0.5f);
  }

  void drawEvent(const Event& event, const Segment& seg,
                 uint32_t now, uint8_t segmentId) {
    const unsigned count = seg.virtualLength();
    if (!count) return;
    const uint32_t elapsed = uint32_t(now - event.startMs);
    if (elapsed >= event.params.durationMs) return;
    const uint32_t seed = event.sequence ^ (uint32_t(segmentId) * 0x9e3779b9UL);

    for (unsigned led = 0; led < count; ++led) {
      const Pixel result = RGBBridgeEventFX::render(event.params, uint16_t(led),
          uint16_t(count), elapsed, seed);
      const uint8_t alpha = opacityFor(event, result.alpha);
      if (alpha) blendLogicalPixel(seg, led, event.reverse, result.color, alpha);
      const uint8_t core = opacityFor(event, result.centerAlpha);
      if (core) blendLogicalPixel(seg, led, event.reverse, result.center, core);
    }
  }

  bool parseEvent(JsonObject& command, Event& event, uint32_t startMs) {
    // Explicit segment IDs are required. Never use WLED's main/selected segment.
    JsonArray selectedIds = command["segments"].as<JsonArray>();
    if (selectedIds.isNull()) return false;
    uint64_t mask = 0;
    for (JsonVariant item : selectedIds) {
      if (!item.is<int>()) continue;
      const int id = item.as<int>();
      if (id >= 0 && id < MAX_SEGMENTS && unsigned(id) < strip.getSegmentsNum()
          && strip.getSegment(id).isActive())
        mask |= uint64_t(1) << id;
    }
    if (!mask) return false;

    // Common properties stay at the command root. ALL effect-specific
    // properties (including reverse and the effect colors) live in options.
    JsonObject options = command["options"].as<JsonObject>();
    if (options.isNull()) return false;

    if (!readEffect(command, event.params.effect)) return false;
    event.active = true;
    event.segmentMask = mask;
    if (!command["duration"].isNull()) {
      event.params.durationMs = uint16_t(bound(command["duration"].as<int>(), 50, 10000));
    } else {
      // Optional common speed supports the existing RGBBridge speed slider.
      const int speed = bound(command["speed"] | 200, 0, 255);
      event.params.durationMs = uint16_t(1000 - speed*900/255);
    }
    event.overlay = command["overlay"] | true;
    const int brightness = command["brightness"].isNull()
      ? (command["intensity"] | 255) : command["brightness"].as<int>();
    event.brightness = uint8_t(bound(brightness, 0, 255));
    readColor(command, "backgroundColor", event.background);

    switch (event.params.effect) {
      case Effect::Projectile:
        readColor(options, "color", event.params.color);
        event.params.pointSize = uint8_t(bound(options["pointSize"] | 2, 1, 32));
        event.params.tailSize = uint8_t(bound(options["tailSize"] | 5, 0, 64));
        event.reverse = options["reverse"] | false;
        break;
      case Effect::Shockwave:
        readColor(options, "colorA", event.params.colorA);
        readColor(options, "colorB", event.params.colorB);
        event.params.waveWidth = uint8_t(bound(options["waveWidth"] | 3, 1, 32));
        break;
      case Effect::Flash:
        readColor(options, "color", event.params.color);
        event.params.holdMs = uint16_t(bound(options["holdMs"] | 40, 0, 10000));
        break;
      case Effect::Pulse:
        readColor(options, "color", event.params.color);
        event.params.pulses = uint8_t(bound(options["pulses"] | 2, 1, 20));
        break;
      case Effect::Progress:
        readColor(options, "color", event.params.color);
        event.reverse = options["reverse"] | false;
        break;
      case Effect::Sparks: {
        readColor(options, "color", event.params.color);
        JsonArray second = options["colorB"].as<JsonArray>();
        event.params.hasSecondSparkColor = !second.isNull() && second.size() >= 3;
        readColor(options, "colorB", event.params.colorB);
        event.params.sparkDensity = uint8_t(bound(options["sparkDensity"] | 12, 1, 100));
        event.params.sparkLifeMs = uint16_t(bound(options["sparkLifeMs"] | 90, 30, 1000));
        break;
      }
    }
    event.startMs = startMs;
    return true;
  }

  // AI: below section was generated by an AI
  // Validate the complete batch before replacing any shot. All effects from
  // one trigger share their timestamp; a slot reserved by this batch cannot
  // be replaced by a later item in that same batch, even during a full burst.
  void enqueue(JsonObject& command) {
    Event pending[MAX_EFFECTS_PER_SHOT];
    uint8_t count = 0;
    const uint32_t startMs = millis();
    if (command.containsKey("effects")) {
      JsonArray effects = command["effects"].as<JsonArray>();
      if (effects.isNull() || effects.size() == 0 || effects.size() > MAX_EFFECTS_PER_SHOT) return;
      uint64_t seen = 0;
      for (JsonVariant item : effects) {
        JsonObject effect = item.as<JsonObject>();
        if (effect.isNull() || !parseEvent(effect, pending[count], startMs)) return;
        if (seen & pending[count].segmentMask) return;
        seen |= pending[count].segmentMask;
        ++count;
      }
    } else {
      if (!parseEvent(command, pending[0], startMs)) return;
      count = 1;
    }
    const uint32_t shotSequence = ++nextShotSequence;
    for (uint8_t item = 0; item < count; ++item)
      pending[item].shotSequence = shotSequence;

    // Preserve eight complete shots even when each shot contains multiple
    // segment-specific definitions. Evict every definition of the oldest shot
    // together; never leave a partially rendered shot in the buffer.
    uint32_t liveShots[MAX_SHOTS] = {};
    uint8_t liveShotCount = 0;
    for (const Event& event : events) {
      if (!isLive(event, startMs)) continue;
      bool known = false;
      for (uint8_t i = 0; i < liveShotCount; ++i)
        if (liveShots[i] == event.shotSequence) { known = true; break; }
      if (!known && liveShotCount < MAX_SHOTS) liveShots[liveShotCount++] = event.shotSequence;
    }
    if (liveShotCount >= MAX_SHOTS) {
      ++evictedShots;
      uint32_t oldest = liveShots[0];
      for (uint8_t i = 1; i < liveShotCount; ++i)
        if (int32_t(liveShots[i] - oldest) < 0) oldest = liveShots[i];
      for (Event& event : events)
        if (event.active && event.shotSequence == oldest) event.active = false;
    }

    bool reserved[MAX_EVENTS] = {};
    for (uint8_t item = 0; item < count; ++item) {
      int slot = -1;
      for (uint8_t i = 0; i < MAX_EVENTS; ++i) {
        if (!reserved[i] && !isLive(events[i], startMs)) { slot = i; break; }
      }
      if (slot < 0) return; // MAX_SHOTS * MAX_EFFECTS_PER_SHOT guarantees capacity.
      reserved[slot] = true;
      pending[item].sequence = ++nextSequence;
      events[slot] = pending[item];
    }
    ++acceptedShots;
    strip.trigger();
  }
  // AI: end

public:
  void setup() override { initDone = true; }

  // AI: below section was generated by an AI
  // Report the compiled capability without triggering an animation.
  void addToJsonInfo(JsonObject& root) override {
    JsonObject fireInfo = root.createNestedObject("RGBBridgeEventFX");
    fireInfo["version"] = "1.4.3";
    fireInfo["nonBlockingSerial"] = true;
    fireInfo["acceptedShots"] = acceptedShots;
    fireInfo["evictedShots"] = evictedShots;
    fireInfo["activeFrames"] = activeFrames;
    fireInfo["maxActiveFrameGapMs"] = maxActiveFrameGapMs;
    fireInfo["batchEffects"] = true;
    fireInfo["returnFadeMs"] = returnFadeMs;
    fireInfo["maxShots"] = MAX_SHOTS;
    fireInfo["maxConfigurationsPerShot"] = MAX_EFFECTS_PER_SHOT;
    fireInfo["maxSegments"] = MAX_SEGMENTS;
    fireInfo["speedContinuity"] = true;
  }
  // AI: end

  // AI: below section was generated by an AI
  // WLED exposes these persisted fields automatically in Config > Usermods.
  void addToConfig(JsonObject& root) override {
    JsonObject config = root.createNestedObject("RGBBridgeEventFX");
    config["returnFadeMs"] = returnFadeMs;
  }

  // Validate at the configuration boundary; zero means immediate return.
  bool readFromConfig(JsonObject& root) override {
    JsonObject config = root["RGBBridgeEventFX"];
    const bool hadNewConfig = !config.isNull();
    if (!hadNewConfig) config = root["RGBBridgeFire"]; // migrate only the saved setting, never the legacy command
    returnFadeMs = uint16_t(bound(config["returnFadeMs"] | 300, 0, 10000));
    return hadNewConfig && !config["returnFadeMs"].isNull();
  }

  void appendConfigData() override {
    oappend(F("addInfo('RGBBridgeEventFX:returnFadeMs',1,' ms - native effect fade-in after the shot (0-10000; 0 = immediate)');"));
  }
  // AI: end

  void readFromJsonState(JsonObject& root) override {
    if (!initDone) return;
    JsonObject command = root["RGBBridgeEventFX"].as<JsonObject>();
    if (!command.isNull() && (command["trigger"] | false)) enqueue(command);
  }

  void loop() override {
    if (!initDone) return;
    const uint32_t now = millis();
    bool any = false, expired = false;
    for (Event& event : events) {
      if (!event.active) continue;
      if (!isLive(event, now)) { event.active = false; expired = true; }
      else any = true;
    }
    // AI: below section was generated by an AI
    for (ReturnFade& fade : returns) {
      if (!fade.active) continue;
      if (int32_t(now - fade.startMs) >= 0 && uint32_t(now - fade.startMs) >= fade.durationMs) {
        fade.active = false;
        expired = true;
      } else any = true;
    }
    // AI: end
    if (expired) strip.trigger(); // Restore WLED's native effect/background.
    if (any && uint32_t(now - lastKickMs) >= FRAME_MS) {
      lastKickMs = now;
      strip.trigger();
    }
  }

  void handleOverlayDraw() override {
    if (!initDone) return;
    const uint32_t now = millis();
    // AI: below section was generated by an AI
    // Count actual overlay frame gaps, including the frame that ends a shot,
    // without treating an idle period between bursts as a rendering pause.
    if (previousFrameActive)
      maxActiveFrameGapMs = std::max(maxActiveFrameGapMs, uint32_t(now - previousFrameMs));
    previousFrameActive = false;
    for (const Event& event : events) previousFrameActive |= isLive(event, now);
    if (previousFrameActive) ++activeFrames;
    previousFrameMs = now;
    // AI: end
    const unsigned count = strip.getSegmentsNum();
    for (unsigned id = 0; id < count && id < MAX_SEGMENTS; ++id) {
      const Segment& seg = strip.getSegment(id);
      if (!seg.isActive() || !seg.on || seg.is2D()) { returns[id].active = false; continue; }

      // Small ordered list ensures the newest event is always drawn last.
      const Event* ordered[MAX_EVENTS];
      uint8_t used = 0;
      for (const Event& event : events) {
        if (!isLive(event, now) || !(event.segmentMask & (uint64_t(1) << id)))
          continue;
        uint8_t pos = used;
        while (pos > 0 && int32_t(event.sequence - ordered[pos-1]->sequence) < 0) {
          ordered[pos] = ordered[pos-1];
          --pos;
        }
        ordered[pos] = &event;
        ++used;
      }
      if (!used) { drawReturn(id, seg, now); continue; }
      const Event& newest = *ordered[used-1];
      // AI: below section was generated by an AI
      // Finish every event on this segment before returning its live native frame.
      uint32_t remaining = 0;
      for (uint8_t i = 0; i < used; ++i)
        remaining = std::max(remaining, uint32_t(ordered[i]->params.durationMs - uint32_t(now - ordered[i]->startMs)));
      ReturnFade& fade = returns[id];
      fade.active = !newest.overlay && returnFadeMs > 0;
      fade.startMs = now + remaining;
      fade.durationMs = returnFadeMs;
      fade.start = seg.start; fade.stop = seg.stop;
      fade.background = color_fade(RGBW32(newest.background.r, newest.background.g, newest.background.b, 0), newest.brightness);
      // AI: end
      if (!newest.overlay) fillBackground(seg, newest.background, newest.brightness);
      for (uint8_t i = 0; i < used; ++i)
        drawEvent(*ordered[i], seg, now, uint8_t(id));
    }
  }
};

static RGBBridgeEventFXUsermod rgbBridgeEventFXUsermod;
REGISTER_USERMOD(rgbBridgeEventFXUsermod);
